'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getState: () => ipcRenderer.invoke('get:state'),
  exportData: (lang) => ipcRenderer.invoke('data:export', lang),
  importData: (lang) => ipcRenderer.invoke('data:import', lang),
  onState: (cb) => ipcRenderer.on('state', (e, v) => cb(v)),
  onWindowResizing: (cb) => ipcRenderer.on('win:resizing', (e, on) => cb(!!on)),
  onWindowFocus: (cb) => ipcRenderer.on('win:focus', (e, focused) => cb(!!focused)),
  setProfile: (data) => ipcRenderer.invoke('profile:set', data),
  setTheme: (theme) => ipcRenderer.invoke('theme:set', theme),
  setFont: (size) => ipcRenderer.invoke('font:set', size),
  setLang: (lang) => ipcRenderer.invoke('lang:set', lang),
  createTeam: (payload) => ipcRenderer.invoke('team:create', payload),
  pickFolder: (defaultPath) => ipcRenderer.invoke('files:pickFolder', defaultPath),
  changeTeamFilesRoot: (payload) => ipcRenderer.invoke('team:changeFilesRoot', payload),
  joinTeam: (payload) => ipcRenderer.invoke('team:join', payload),
  deviceLink: (payload) => ipcRenderer.invoke('team:deviceLink', payload),
  deviceCodes: (teamId) => ipcRenderer.invoke('team:deviceCodes', teamId),
  deviceSetCode: (payload) => ipcRenderer.invoke('team:deviceSetCode', payload),
  deviceResetCode: (payload) => ipcRenderer.invoke('team:deviceResetCode', payload),
  viewerCode: (teamId) => ipcRenderer.invoke('team:viewerCode', teamId),
  viewerSetCode: (payload) => ipcRenderer.invoke('team:viewerSetCode', payload),
  viewerResetCode: (teamId) => ipcRenderer.invoke('team:viewerResetCode', teamId),
  portalCode: () => ipcRenderer.invoke('portal:code'),
  portalSetCode: (code) => ipcRenderer.invoke('portal:setCode', code),
  portalLink: () => ipcRenderer.invoke('portal:link'),
  cancelJoin: () => ipcRenderer.invoke('team:cancelJoin'),
  approve: (payload) => ipcRenderer.invoke('team:approve', payload),
  reject: (payload) => ipcRenderer.invoke('team:reject', payload),
  action: (teamId, type, payload) => ipcRenderer.invoke('team:action', { teamId, type, payload }),
  switchTeam: (teamId) => ipcRenderer.invoke('team:switch', teamId),
  refreshTeam: (teamId) => ipcRenderer.invoke('team:refresh', teamId),
  leaveTeam: (teamId) => ipcRenderer.invoke('team:leave', { teamId }),
  copy: (text) => ipcRenderer.invoke('clip', text),
  pin: (on) => ipcRenderer.invoke('win:pin', on),
  mini: (on, height, topOffset, duration) => ipcRenderer.invoke('win:mini', { on, height, topOffset, duration }),
  miniNow: (on, height, topOffset) => ipcRenderer.sendSync('win:miniNow', { on, height, topOffset }),
  miniStep: (topDev, botDev) => ipcRenderer.sendSync('win:miniStep', { topDev, botDev }),
  miniBegin: (height, topDev) => ipcRenderer.sendSync('win:miniBegin', { height, topDev }),
  miniFrame: (tp, bp) => ipcRenderer.send('win:miniFrame', { tp, bp }),
  miniCommit: () => ipcRenderer.invoke('win:miniCommit'),
  miniCommitNow: () => ipcRenderer.sendSync('win:miniCommitNow'),
  miniAnchor: (offsetDev) => ipcRenderer.sendSync('win:miniAnchor', { offsetDev }),
  min: () => ipcRenderer.send('win:min'),
  close: () => ipcRenderer.send('win:close'),
  dragStart: () => ipcRenderer.send('win:dragStart'),
  dragMove: (dx, dy) => ipcRenderer.send('win:dragMove', { dx, dy }),
  dragEnd: () => ipcRenderer.send('win:dragEnd'),
  quit: () => ipcRenderer.send('app:quit'),
  setAutoStart: (on) => ipcRenderer.invoke('app:autostart', on),
  setRelayUrl: (url) => ipcRenderer.invoke('relay:set', url),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  markUpdateSeen: (version) => ipcRenderer.invoke('update:seen', version),
  onUpdateAvailable: (cb) => ipcRenderer.on('update:available', (e, info) => cb(info || {})),
  setNotify: (data) => ipcRenderer.invoke('notify:set', data),
  onOpenTask: (cb) => ipcRenderer.on('notification:openTask', (e, payload) => cb(payload || {})),
  open: (url) => ipcRenderer.invoke('open:external', url),
  openPath: (target) => ipcRenderer.invoke('open:path', target),
  attachFile: (payload) => ipcRenderer.invoke('task:attachFile', payload),
  openTaskFile: (payload) => ipcRenderer.invoke('task:openFile', payload),
  openTaskFolder: (payload) => ipcRenderer.invoke('task:openFolder', payload),
  previewTaskFile: (payload) => ipcRenderer.invoke('task:previewFile', payload),
  submitTaskFile: (payload) => ipcRenderer.invoke('task:submitFile', payload),
  filesInfo: () => ipcRenderer.invoke('files:info'),
  aiGreeted: () => ipcRenderer.invoke('ai:greeted'),
  requestSummary: (teamId, taskId, note) => ipcRenderer.invoke('ai:requestSummary', { teamId, taskId, note })
});
